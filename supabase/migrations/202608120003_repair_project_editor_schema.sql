-- Repairs a partially migrated database used by the project editor.
-- This migration is intentionally idempotent and can be run directly in
-- Supabase SQL Editor even if earlier project-editor migrations ran in part.

create table if not exists public.project_statuses (
  code text primary key,
  name text not null unique,
  is_terminal boolean not null default false,
  sort_order integer not null default 0,
  is_active boolean not null default true
);

insert into public.project_statuses (code, name, is_terminal, sort_order)
values
  ('in_development', 'В разработке', false, 10),
  ('completed', 'Завершён', true, 20)
on conflict (code) do update
set
  name = excluded.name,
  is_terminal = excluded.is_terminal,
  sort_order = excluded.sort_order;

create table if not exists public.directions (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  is_active boolean not null default true
);

insert into public.project_types (name, weight)
select 'Модульная программа', 1
where not exists (
  select 1
  from public.project_types
  where lower(btrim(name)) = lower('Модульная программа')
);

alter table public.project_names
  add column if not exists status_code text not null default 'in_development'
    references public.project_statuses(code) on delete restrict,
  add column if not exists project_type_id bigint
    references public.project_types(id) on delete restrict,
  add column if not exists parent_project_id bigint
    references public.project_names(id) on delete restrict,
  add column if not exists module_position integer,
  add column if not exists customer text,
  add column if not exists lead_methodologist_id bigint
    references public.trainers(id) on delete set null,
  add column if not exists target_audience text,
  add column if not exists goals text,
  add column if not exists short_description text,
  add column if not exists duration_days numeric,
  add column if not exists duration_hours numeric;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.project_names'::regclass
      and conname = 'project_names_status_code_fkey'
  ) then
    alter table public.project_names
      add constraint project_names_status_code_fkey
      foreign key (status_code) references public.project_statuses(code) on delete restrict;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.project_names'::regclass
      and conname = 'project_names_project_type_id_fkey'
  ) then
    alter table public.project_names
      add constraint project_names_project_type_id_fkey
      foreign key (project_type_id) references public.project_types(id) on delete restrict;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.project_names'::regclass
      and conname = 'project_names_parent_project_id_fkey'
  ) then
    alter table public.project_names
      add constraint project_names_parent_project_id_fkey
      foreign key (parent_project_id) references public.project_names(id) on delete restrict;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.project_names'::regclass
      and conname = 'project_names_lead_methodologist_id_fkey'
  ) then
    alter table public.project_names
      add constraint project_names_lead_methodologist_id_fkey
      foreign key (lead_methodologist_id) references public.trainers(id) on delete set null;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.project_names'::regclass
      and conname = 'project_names_not_own_parent'
  ) then
    alter table public.project_names
      add constraint project_names_not_own_parent
      check (parent_project_id is null or parent_project_id <> id);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.project_names'::regclass
      and conname = 'project_names_module_position_positive'
  ) then
    alter table public.project_names
      add constraint project_names_module_position_positive
      check (module_position is null or module_position > 0);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.project_names'::regclass
      and conname = 'project_names_duration_days_non_negative'
  ) then
    alter table public.project_names
      add constraint project_names_duration_days_non_negative
      check (duration_days is null or duration_days >= 0);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.project_names'::regclass
      and conname = 'project_names_duration_hours_non_negative'
  ) then
    alter table public.project_names
      add constraint project_names_duration_hours_non_negative
      check (duration_hours is null or duration_hours >= 0);
  end if;
end;
$$;

-- Preserve the old program classification when the legacy column still exists.
do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'project_names'
      and column_name = 'kind_code'
  ) then
    execute $migration$
      update public.project_names as project
      set project_type_id = modular_type.id
      from (
        select min(id) as id
        from public.project_types
        where lower(btrim(name)) = lower('Модульная программа')
      ) as modular_type
      where project.kind_code = 'program'
        and modular_type.id is not null
    $migration$;
  end if;
end;
$$;

