create or replace function public.prevent_project_hierarchy_cycle()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.parent_project_id is null then
    return new;
  end if;

  if new.parent_project_id = new.id then
    raise exception 'A project cannot be its own parent';
  end if;

  if exists (
    with recursive ancestors as (
      select p.id, p.parent_project_id
      from public.project_names p
      where p.id = new.parent_project_id

      union all

      select p.id, p.parent_project_id
      from public.project_names p
      join ancestors a on p.id = a.parent_project_id
    )
    select 1 from ancestors where id = new.id
  ) then
    raise exception 'A project hierarchy cycle is not allowed';
  end if;

  return new;
end;
$$;

drop trigger if exists prevent_project_hierarchy_cycle on public.project_names;
create trigger prevent_project_hierarchy_cycle
before insert or update of parent_project_id
on public.project_names
for each row
execute function public.prevent_project_hierarchy_cycle();

create or replace function public.validate_project_module_parent()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.parent_project_id is not null and not exists (
    select 1
    from public.project_names as parent
    join public.project_types as parent_type
      on parent_type.id = parent.project_type_id
    where parent.id = new.parent_project_id
      and lower(btrim(parent_type.name)) = lower('Модульная программа')
  ) then
    raise exception 'Modules can only be added to a project of type "Модульная программа"'
      using errcode = '23514';
  end if;

  if exists (
    select 1
    from public.project_names as child
    where child.parent_project_id = new.id
  ) and not exists (
    select 1
    from public.project_types as current_type
    where current_type.id = new.project_type_id
      and lower(btrim(current_type.name)) = lower('Модульная программа')
  ) then
    raise exception 'A project with modules must have type "Модульная программа"'
      using errcode = '23514';
  end if;

  return new;
end;
$$;

drop trigger if exists validate_project_module_parent on public.project_names;
create trigger validate_project_module_parent
before insert or update of parent_project_id, project_type_id
on public.project_names
for each row
execute function public.validate_project_module_parent();

notify pgrst, 'reload schema';
