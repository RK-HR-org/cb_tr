create or replace function public.save_program_schedule(
  p_program_project_id bigint,
  p_start_date date,
  p_gap_value integer,
  p_gap_unit text,
  p_calendar_mode text,
  p_modules jsonb
)
returns bigint
language plpgsql
set search_path = public
as $$
declare
  v_schedule_id bigint;
  v_module jsonb;
  v_module_id bigint;
  v_event_id bigint;
  v_program_name text;
begin
  if p_modules is null or jsonb_array_length(p_modules) = 0 then
    raise exception 'A modular program must contain at least one module' using errcode = '22023';
  end if;

  select name into v_program_name from public.project_names where id = p_program_project_id;
  if v_program_name is null then
    raise exception 'Program % not found', p_program_project_id using errcode = 'P0002';
  end if;

  insert into public.program_schedules (
    program_project_id, start_date, gap_value, gap_unit, calendar_mode
  ) values (
    p_program_project_id, p_start_date, p_gap_value, p_gap_unit, coalesce(nullif(p_calendar_mode, ''), 'working')
  ) returning id into v_schedule_id;

  for v_module in select value from jsonb_array_elements(p_modules) loop
    insert into public.program_schedule_modules (
      schedule_id, module_project_id, module_position, duration_days,
      planned_start_date, planned_end_date
    ) values (
      v_schedule_id,
      (v_module->>'module_project_id')::bigint,
      (v_module->>'module_position')::integer,
      (v_module->>'duration_days')::numeric,
      (v_module->>'planned_start_date')::date,
      (v_module->>'planned_end_date')::date
    ) returning id into v_module_id;

    insert into public.admin_calendar_events (
      project_main_id,
      title,
      required_trainer_count,
      start_date,
      end_date,
      description,
      comments,
      occurrence_index,
      program_schedule_id,
      program_schedule_module_id
    ) values (
      (v_module->>'module_project_id')::bigint,
      coalesce((select name from public.project_names where id = (v_module->>'module_project_id')::bigint), 'Модуль'),
      1,
      (v_module->>'planned_start_date')::date,
      (v_module->>'planned_end_date')::date,
      'Модуль программы «' || v_program_name || '»',
      'Создано планированием программы',
      coalesce((v_module->>'module_position')::integer - 1, 0),
      v_schedule_id,
      v_module_id
    ) returning id into v_event_id;

    update public.program_schedule_modules
      set admin_calendar_event_id = v_event_id
      where id = v_module_id;
  end loop;

  return v_schedule_id;
end;
$$;

revoke all on function public.save_program_schedule(bigint, date, integer, text, text, jsonb) from public;
