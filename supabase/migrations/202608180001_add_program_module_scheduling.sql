  add constraint project_names_module_gap_unit_check
  check (module_gap_unit is null or module_gap_unit in ('days', 'weeks', 'months', 'quarters'));

create table if not exists public.program_schedules (
  id bigint generated by default as identity primary key,
  program_project_id integer not null references public.project_names(id) on delete cascade,
  start_date date not null,
  gap_value integer not null,
  gap_unit text not null,
  calendar_mode text not null default 'working',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint program_schedules_gap_value_check check (gap_value >= 0),
  constraint program_schedules_gap_unit_check check (gap_unit in ('days', 'weeks', 'months', 'quarters')),
  constraint program_schedules_calendar_mode_check check (calendar_mode in ('working', 'calendar'))
);

create table if not exists public.program_schedule_modules (
  id bigint generated by default as identity primary key,
  schedule_id bigint not null references public.program_schedules(id) on delete cascade,
  module_project_id integer not null references public.project_names(id) on delete restrict,
  module_position integer,
  duration_days numeric not null,
  planned_start_date date not null,
  planned_end_date date not null,
  admin_calendar_event_id bigint,
  created_at timestamptz not null default now(),
  constraint program_schedule_modules_duration_check check (duration_days > 0),
  constraint program_schedule_modules_dates_check check (planned_end_date >= planned_start_date),
  constraint program_schedule_modules_unique_module unique (schedule_id, module_project_id)
);

alter table public.admin_calendar_events
  add column if not exists program_schedule_id bigint,
  add column if not exists program_schedule_module_id bigint;

create index if not exists program_schedules_program_idx
