create table if not exists public.cities (
  id bigint generated by default as identity primary key,
  name text not null unique,
  is_active boolean not null default true
);

create table if not exists public.divisions (
  id bigint generated by default as identity primary key,
  name text not null unique,
  is_active boolean not null default true
);

create table if not exists public.certification_statuses (
  code text primary key,
  name text not null unique,
  grants_access boolean not null default false,
  sort_order integer not null default 0,
  is_active boolean not null default true
);

insert into public.certification_statuses (
  code,
  name,
  grants_access,
  sort_order,
  is_active
)
values
  ('in_training', 'В процессе сертификации', false, 10, true),
  ('certified', 'Сертифицирован', true, 20, true),
  ('suspended', 'Допуск приостановлен', false, 30, true),
  ('expired', 'Срок действия истёк', false, 40, true)
on conflict (code) do update
set name = excluded.name,
    grants_access = excluded.grants_access,
    sort_order = excluded.sort_order,
    is_active = excluded.is_active;

alter table public.trainers
  add column if not exists city_id bigint,
  add column if not exists division_id bigint;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.trainers'::regclass
      and conname = 'trainers_city_id_fkey'
  ) then
    alter table public.trainers
      add constraint trainers_city_id_fkey
      foreign key (city_id) references public.cities(id) on delete set null;
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.trainers'::regclass
      and conname = 'trainers_division_id_fkey'
  ) then
    alter table public.trainers
      add constraint trainers_division_id_fkey
      foreign key (division_id) references public.divisions(id) on delete set null;
  end if;
end
$$;

create table if not exists public.trainer_certifications (
  id bigint generated by default as identity primary key,
  trainer_id bigint not null references public.trainers(id) on delete cascade,
  project_id bigint not null references public.project_names(id) on delete cascade,
  status_code text not null default 'certified'
    references public.certification_statuses(code) on delete restrict,
  valid_from date,
  valid_until date,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (trainer_id, project_id),
  constraint trainer_certifications_validity_check
    check (valid_until is null or valid_from is null or valid_until >= valid_from)
);

create index if not exists trainers_city_id_idx
  on public.trainers (city_id);
create index if not exists trainers_division_id_idx
  on public.trainers (division_id);
create index if not exists trainer_certifications_trainer_id_idx
  on public.trainer_certifications (trainer_id);
create index if not exists trainer_certifications_project_id_idx
  on public.trainer_certifications (project_id);

create or replace view public.trainer_effective_project_access as
with recursive project_descendants as (
  select
    project.id as granted_project_id,
    project.id as accessible_project_id
  from public.project_names project

  union all

  select
    descendants.granted_project_id,
    child.id as accessible_project_id
  from project_descendants descendants
  join public.project_names child
    on child.parent_project_id = descendants.accessible_project_id
)
select distinct
  certification.trainer_id,
  descendants.accessible_project_id as project_id,
  certification.project_id as granted_by_project_id,
  certification.id as certification_id
from public.trainer_certifications certification
join public.certification_statuses status
  on status.code = certification.status_code
 and status.grants_access
join project_descendants descendants
  on descendants.granted_project_id = certification.project_id
where
  (certification.valid_from is null or certification.valid_from <= current_date)
  and (certification.valid_until is null or certification.valid_until >= current_date);

comment on table public.trainer_certifications is
  'Direct trainer certification records. Program access is inherited by descendant modules.';

